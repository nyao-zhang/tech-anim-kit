# --------------------------------------------------------------------- 工具
def _snapshot(root):
    """目录快照：路径 → 文件字节（目录记为 b"<dir>"），用于硬断言"没写盘"。"""
    result = {}
    for path in sorted(Path(root).rglob("*")):
        key = str(path.relative_to(root))
        result[key] = b"<dir>" if path.is_dir() else path.read_bytes()
    return result


def _entry(root, target="maya"):
    return Path(root) / TARGETS[target]["entry_file"]


def _write(path, text):
    """按字节写文本，绕开 Windows 的 \n → \r\n 自动转换。"""
    Path(path).write_bytes(text.encode("utf-8"))


def _read(path):
    """按字节读文本，保留 CRLF 原样，便于逐字节比对。"""
    return Path(path).read_bytes().decode("utf-8")


def _plan(repo, root, target="maya", dry_run=True):
    return plan_install(repo, targets=[target], roots={target: str(root)},
                        dry_run=dry_run)


def _install(repo, root, target="maya"):
    plan = _plan(repo, root, target, dry_run=False)
    return plan, apply_plan(plan)


def _backups(path):
    return sorted(Path(path).parent.glob(Path(path).name + ".tak-backup-*"))


