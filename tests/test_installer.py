def test_install_sources_have_no_dcc_imports():
    import ast

    forbidden = {"maya", "pymxs", "pyfbsdk", "unreal"}
    for name in ("__init__.py", "targets.py", "writer.py", "cli.py", "__main__.py"):
        path = REPO_ROOT / "tak" / "install" / name
        tree = ast.parse(_read(path), filename=str(path))
        for node in ast.walk(tree):
            if isinstance(node, ast.Import):
                roots = [alias.name.split(".")[0] for alias in node.names]
            elif isinstance(node, ast.ImportFrom):
                roots = [node.module.split(".")[0]] if node.module and node.level == 0 else []
            else:
                continue
            assert not (set(roots) & forbidden), (name, roots)


