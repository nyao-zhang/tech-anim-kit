def test_apply_backup_counter_increments_without_overwrite(repo, maya):
    path = _entry(maya)
    _write(path, "USER = 1\n")
    _install(repo, maya)

    first_backup = _backups(path)[0]
    first_backup_bytes = first_backup.read_bytes()

    # 用户手改块内内容 → 再次 apply 会 replace-block，产生第二个备份
    text = _read(path).replace("tak_launch = None", "tak_launch = 1")
    _write(path, text)
    _install(repo, maya)

    backups = _backups(path)
    assert [item.name.rsplit("-", 1)[-1] for item in backups] == ["1", "2"]
    assert first_backup.read_bytes() == first_backup_bytes
    assert "tak_launch = 1" in _read(backups[1])
    assert "tak_launch = None" in _read(path)


