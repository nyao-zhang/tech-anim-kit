def test_plan_never_opens_files_for_writing(repo, maya, monkeypatch):
    path = _entry(maya)
    _write(path, "USER = 1\n")
    real_open = builtins.open
    writes = []

    def spy(file, mode="r", *args, **kwargs):
        if any(flag in str(mode) for flag in ("w", "a", "x", "+")):
            writes.append((str(file), str(mode)))
        return real_open(file, mode, *args, **kwargs)

    monkeypatch.setattr(builtins, "open", spy)
    plan = plan_install(repo, targets=["maya"], roots={"maya": str(maya)})
    assert plan.actions[0].mode == "append"
    assert writes == []


