"""四端安装目标定义与探测。

设计约束
--------
* 纯 Python 3.9+、零第三方依赖；**不 import 任何 DCC 模块**。
  安装器只负责写文件，不启动宿主，因此 ``maya`` / ``pymxs`` /
  ``pyfbsdk`` / ``unreal`` 连 ``try/except`` 都不需要。
* 所有路径模板只做字符串展开，不触碰文件系统（除探测时的 ``os.path.isdir``）。
* 每个 target 的注入块都是**自包含、幂等**的：sys.path 先判重，
  宿主 API 调用全部包在 ``try/except`` 里，重复执行不产生副作用。

路径模板占位符
--------------
``{home}``         用户主目录
``{documents}``    文档目录（Windows 为 ``~/Documents``，macOS 同为 ``~/Documents``）
``{localappdata}`` Windows 本地 AppData（3ds Max 真实用户脚本目录在此）
``{version}``      DCC 主版本号，如 ``2023``
``{project}``      UE 项目根目录（仅 ``TAK_UE_PROJECT`` 提供）
"""
