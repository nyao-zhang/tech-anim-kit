def _payload(template: str, style: str = "hash") -> str:
    """把 ``%HINT%`` 占位替换成对应注释风格的"请勿手改"提示行。"""
    hint = _HINT_DASH if style == "dash" else _HINT_HASH
    return template.replace("%HINT%", hint)


