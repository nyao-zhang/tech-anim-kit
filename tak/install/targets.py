#: 探测顺序（与 TARGETS 声明顺序一致，便于输出稳定）
TARGET_ORDER = ("maya", "max", "mobu", "unreal")

_VERSION_DIR_RE = re.compile(r"^(\d{4})")


# --------------------------------------------------------------------- 路径展开
def _home() -> str:
    """用户主目录；独立成函数便于测试 monkeypatch。"""
    return os.path.expanduser("~")


def _documents() -> str:
    """文档目录；macOS / Windows 都取 ``~/Documents``。"""
    return os.path.join(_home(), "Documents")


def _localappdata() -> str:
    """Windows 本地 AppData；非 Windows 退化为 ``~/.local/share``。"""
    value = os.environ.get("LOCALAPPDATA")
    if value:
        return value
    if os.name == "nt":
        return os.path.join(_home(), "AppData", "Local")
    return os.path.join(_home(), ".local", "share")


def _platform_kind() -> str:
    """当前平台标识：``windows`` / ``macos`` / ``linux``。"""
    if os.name == "nt":
        return "windows"
    if sys.platform == "darwin":
        return "macos"
    return "linux"


def _expand(template: str, version: str = "") -> str:
    """展开路径模板；缺少 ``{project}`` 等必需值时返回空串。"""
    if not template:
        return ""
    project = os.environ.get("TAK_UE_PROJECT", "")
    values = {
        "{home}": _home(),
        "{documents}": _documents(),
        "{localappdata}": _localappdata(),
        "{version}": version,
        "{project}": project,
    }
    result = template
    for key, value in values.items():
        if key in result:
            if not value:
                return ""
            result = result.replace(key, value)
    return os.path.normpath(result)


def _candidate_specs(spec: Dict[str, Any]) -> List[Dict[str, str]]:
    """按当前平台筛选候选（**整条**定义，含可选的 ``probe``）。"""
    platform = _platform_kind()
    matched = [item for item in spec["default_roots"]
               if item["os"] in (platform, "any")]
    return matched or list(spec["default_roots"])


def _candidate_templates(spec: Dict[str, Any]) -> List[str]:
    """按当前平台筛选候选模板；没有平台匹配时退回全部候选。"""
    return [item["template"] for item in _candidate_specs(spec)]


# --------------------------------------------------------------------- 版本探测
def _version_dirs(parent: str, min_version: str) -> List[str]:
    """列出 ``parent`` 下形如 ``2023`` / ``2024 - 64bit`` 的版本目录。"""
    try:
        names = os.listdir(parent)
    except OSError:
        return []
    found = set()
    for name in names:
        match = _VERSION_DIR_RE.match(name)
        if match and match.group(1) >= min_version:
            found.add(match.group(1))
    return sorted(found)


def _resolve_version(target_id: str, spec: Dict[str, Any]) -> str:
    """版本优先级：环境变量 → 已安装目录里最高的版本 → ``min_version``。"""
    env_version = os.environ.get(ENV_VERSIONS.get(target_id, ""), "").strip()
    if env_version:
        return env_version
    scan = spec.get("version_scan") or []
    if isinstance(scan, str):
        scan = [scan]
    version = ""
    for parent_template in scan:
        parent = _expand(parent_template, "")
        for found in _version_dirs(parent, spec["min_version"]):
            if found > version:
                version = found
    return version or spec["min_version"]


# --------------------------------------------------------------------- 探测入口
def detect_targets(roots: Optional[Dict[str, str]] = None) -> Dict[str, Dict[str, Any]]:
    """探测四端安装根目录。

    优先级：显式 ``roots`` 参数（CLI ``--root``）→ 环境变量
    （``TAK_MAYA_ROOT`` 等）→ ``default_roots`` 模板存在性检查。

    :param roots: ``{"maya": "C:/tmp/maya"}`` 形式的显式覆盖；显式值即使
        尚不存在也视为 ``found=True``（安装器会创建目录）。
    :return: ``{"maya": {"found": bool, "root": str, "entry": str, "version": str}, ...}``
        目录不存在不是错误，只是 ``found=False``。
    """
    overrides = dict(roots or {})
    detected: Dict[str, Dict[str, Any]] = {}
    for target_id in TARGET_ORDER:
        spec = TARGETS[target_id]
        version = _resolve_version(target_id, spec)
        root = ""
        explicit = False
        detected_dir = False

        override = overrides.get(target_id)
        if override:
            root = os.path.normpath(os.path.expanduser(override))
            explicit = True
        else:
            env_root = os.environ.get(ENV_ROOTS[target_id], "").strip()
            if env_root:
                root = os.path.normpath(os.path.expanduser(env_root))
            else:
                for item in _candidate_specs(spec):
                    candidate = _expand(item.get("template", ""), version)
                    if not candidate:
                        continue
                    # ``probe`` 存在而 ``template`` 尚未创建时，仍认定已安装：
                    # 目录由 writer 在写入前 makedirs。
                    evidence = _expand(item.get("probe") or "", version) or candidate
                    if os.path.isdir(evidence):
                        root = candidate
                        detected_dir = True
                        break

        # 显式 --root 或环境变量：即使目录还不存在也算可用（安装器会创建）；
        # 自动探测：``probe`` 命中即可，写入根目录允许尚不存在。
        found = bool(root) and (explicit or detected_dir or os.path.isdir(root))
        entry = os.path.join(root, spec["entry_file"]) if found else ""
        detected[target_id] = {
            "found": found,
            "root": root,
            "entry": entry,
            "version": version,
            "explicit": explicit,
        }
    return detected


